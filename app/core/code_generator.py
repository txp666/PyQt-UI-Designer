def generate_project(project: ProjectData, output_dir: str):
    """Generate a complete standalone Python project from project data."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    # requirements.txt
    (out / "requirements.txt").write_text(
        "PyQt-Fluent-Widgets>=1.5.5\npyserial>=3.5\npyqtgraph>=0.13.3\n",
        encoding="utf-8",
    )

    # main.py
    (out / "main.py").write_text(_gen_main(), encoding="utf-8")

    # ui.py
    (out / "ui.py").write_text(
        _gen_ui(project.widgets, project.canvas_width, project.canvas_height, project.app_name),
        encoding="utf-8",
    )

    # serial_handler.py
    (out / "serial_handler.py").write_text(
        _gen_serial_handler(project.serial),
        encoding="utf-8",
    )

    # data_binding.py
    bindings = _extract_bindings(project.widgets)
    widget_types = {w["type"] for w in project.widgets}
    (out / "data_binding.py").write_text(
        _gen_data_binding(bindings, widget_types),
        encoding="utf-8",
    )

    # copy logo.ico if exists
    import shutil
    _root = Path(__file__).resolve().parent.parent.parent
    _ico = _root / "logo.ico"
    if _ico.exists():
        shutil.copy2(str(_ico), str(out / "logo.ico"))


