def _extract_bindings(widgets: list) -> list:
    bindings = []
    def _walk(items):
        for w in items:
            b = w.get("binding")
            if b:
                pm = b.get("parseMode", "键值匹配")
                has_config = (
                    (pm == "键值匹配" and b.get("key"))
                    or (pm == "JSON路径" and b.get("jsonPath"))
                    or (pm == "HEX字节提取")
                    or (pm == "Modbus")
                )
                if has_config:
                    props = w.get("properties", {})
                    entry = {
                        "widget_id": w["id"],
                        "type": w["type"],
                        "parseMode": pm,
                        "key": b.get("key", ""),
                        "jsonPath": b.get("jsonPath", ""),
                        "byteOffset": int(b.get("byteOffset", 0)),
                        "dataType": b.get("dataType", "uint16"),
                        "byteOrder": b.get("byteOrder", "大端(BE)"),
                        "expression": b.get("expression"),
                        "displayFormat": props.get("displayFormat", "自动"),
                        "frameHeader": b.get("frameHeader", ""),
                        "frameTail": b.get("frameTail", ""),
                        "mbRegIndex": int(b.get("mbRegIndex", 0)),
                        "mbDataType": b.get("mbDataType", "uint16"),
                        "mbRegOrder": b.get("mbRegOrder", "大端(AB CD)"),
                        "mbFcFilter": int(b.get("mbFcFilter", -1)),
                        "mbSlaveFilter": int(b.get("mbSlaveFilter", -1)),
                    }
                    if w["type"] == "LEDIndicator":
                        entry["onValue"] = str(props.get("onValue", "1"))
                        entry["offValue"] = str(props.get("offValue", "0"))
                    bindings.append(entry)
            _walk(w.get("children", []))
    _walk(widgets)
    return bindings


def _gen_data_binding(bindings: list, widget_types: set = None) -> str:
    has_parsed = any(b["parseMode"] in ("键值匹配", "JSON路径", "Modbus") for b in bindings)
    has_hex = any(b["parseMode"] == "HEX字节提取" for b in bindings)
    has_chart = widget_types and "RealtimeChart" in widget_types

    lines = [
        '# coding: utf-8',
        '"""Auto-generated data binding."""',
        'import struct',
    ]
    if has_chart:
        lines.append('from ui import RealtimeLineChart')
    if has_hex:
        lines.append('from serial_handler import RawFrameBuffer')
    lines.append('')

    lines += [
        '',
        'def _format_display(value, fmt):',
        '    if fmt == "自动": return value',
        '    try:',
        '        num = int(float(value)) if not isinstance(value, int) else value',
        '    except (ValueError, TypeError): return value',
        '    if fmt == "十六进制(HEX)":',
        '        return f"0x{num:02X}" if num >= 0 else f"-0x{abs(num):02X}"',
        '    if fmt == "二进制(BIN)":',
        '        return f"0b{num:08b}" if num >= 0 else f"-0b{abs(num):08b}"',
        '    if fmt == "十进制": return str(num)',
        '    return value',
        '',
        '',
        'def _resolve_path(data, path):',
        '    for part in path.split("."):',
        '        if data is None: return None',
        '        if isinstance(data, dict): data = data.get(part)',
        '        elif isinstance(data, (list, tuple)):',
        '            try: data = data[int(part)]',
        '            except (ValueError, IndexError): return None',
        '        else: return None',
        '    return data',
        '',
        '',
        '_STRUCT_FMT = {',
        '    "uint8": ("B", 1), "int8": ("b", 1),',
        '    "uint16": ("H", 2), "int16": ("h", 2),',
        '    "uint32": ("I", 4), "int32": ("i", 4),',
        '    "float32": ("f", 4),',
        '}',
        '',
        '',
        'class DataBinding:',
        '    def __init__(self, ui, serial_handler):',
        '        self.ui = ui',
        '        self.serial = serial_handler',
        '        ui._serial_handler = serial_handler',
        '        for w in ui.widgets.values():',
        '            if hasattr(w, "set_serial_handler"):',
        '                w.set_serial_handler(serial_handler)',
    ]
    if has_chart:
        lines += [
            '            if isinstance(w, RealtimeLineChart):',
            '                serial_handler.dataReceived.connect(w.on_parsed)',
            '                serial_handler.rawReceived.connect(w.on_raw)',
            '                serial_handler.disconnected.connect(w.reset_stream)',
        ]

    if has_hex:
        from app.core.data_binding import BindingEntry
        lines.append('        self._raw_frames = {}')
        for binding in bindings:
            if binding["parseMode"] == "HEX字节提取":
                header = BindingEntry._hex_to_bytes(binding.get("frameHeader", ""))
                footer = BindingEntry._hex_to_bytes(binding.get("frameTail", ""))
                lines.append(f'        self._raw_frames[{binding["widget_id"]!r}] = '
                             f'RawFrameBuffer({header!r}, {footer!r})')
    if has_parsed:
        lines.append('        self.serial.dataReceived.connect(self._on_data)')
    if has_hex:
        lines.append('        self.serial.rawReceived.connect(self._on_raw)')
        lines.append('        self.serial.disconnected.connect(self._reset_stream)')
    lines.append('')

    # -- _on_data for 键值匹配 / JSON路径 --
    if has_parsed:
        lines.append('    def _on_data(self, data: dict):')
        parsed_bindings = [b for b in bindings if b["parseMode"] in ("键值匹配", "JSON路径", "Modbus")]
        for b in parsed_bindings:
            _gen_binding_apply(lines, b, source="parsed")
        if not parsed_bindings:
            lines.append('        pass')
        lines.append('')

    # -- _on_raw for HEX字节提取 --
    if has_hex:
        lines += [
            '    def _reset_stream(self):',
            '        for frames in self._raw_frames.values(): frames.reset()',
            '',
        ]
        lines.append('    def _on_raw(self, raw: bytes):')
        hex_bindings = [b for b in bindings if b["parseMode"] == "HEX字节提取"]
        for index, b in enumerate(hex_bindings):
            lines.append(f'        for frame in self._raw_frames[{b["widget_id"]!r}].feed(raw):')
            lines.append(f'            self._raw_binding_{index}(frame)')
        if not hex_bindings:
            lines.append('        pass')
        lines.append('')
        for index, b in enumerate(hex_bindings):
            lines.append(f'    def _raw_binding_{index}(self, raw):')
            _gen_binding_apply(lines, b, source="raw")

    if not has_parsed and not has_hex:
        lines.append('    pass')

    return "\n".join(lines).rstrip() + "\n"


def _gen_binding_apply(lines: list, b: dict, source: str):
    """Generate the value extraction + widget apply code for one binding."""
    wid = b["widget_id"]
    wtype = b["type"]
    expr = b.get("expression")
    dfmt = b.get("displayFormat", "自动")
    pm = b["parseMode"]

    if source == "parsed":
        if pm == "键值匹配":
            key = b["key"]
            lines.append(f"        if {key!r} in data:")
            lines.append(f"            value = data[{key!r}]")
        elif pm == "JSON路径":
            jp = b["jsonPath"]
            lines.append(f"        value = _resolve_path(data, {repr(jp)})")
            lines.append(f"        if value is not None:")
        elif pm == "Modbus":
            reg_idx = b.get("mbRegIndex", 0)
            slave_filter = b.get("mbSlaveFilter", -1)
            fc_filter = b.get("mbFcFilter", -1)
            mb_dt = b.get("mbDataType", "uint16")
            mb_ro = b.get("mbRegOrder", "大端(AB CD)")
            if slave_filter >= 0:
                lines.append(f"        if data.get('slave') != {slave_filter}: value = None")
            if fc_filter >= 0:
                cond = f"data.get('fc') != {fc_filter}"
                if slave_filter >= 0:
                    lines.append(f"        elif {cond}: value = None")
                else:
                    lines.append(f"        if {cond}: value = None")
            guard = "elif" if (slave_filter >= 0 or fc_filter >= 0) else "if"
            lines.append(f"        {guard} data.get('fc', 0) in (1, 2):")
            lines.append(f"            value = data.get(f'coil{reg_idx}')")
            if mb_dt in ("uint16", "int16"):
                lines.append(f"        else:")
                lines.append(f"            value = data.get(f'reg{reg_idx}')")
                if mb_dt == "int16":
                    lines.append(f"            if value is not None and value > 32767: value = value - 65536")
            else:
                lines.append(f"        else:")
                lines.append(f"            _r0 = data.get(f'reg{reg_idx}')")
                lines.append(f"            _r1 = data.get(f'reg{reg_idx + 1}')")
                lines.append(f"            if _r0 is None or _r1 is None: value = None")
                lines.append(f"            else:")
                if mb_ro == "大端(AB CD)":
                    lines.append(f"                _raw = _r0.to_bytes(2,'big') + _r1.to_bytes(2,'big')")
                else:
                    lines.append(f"                _raw = _r1.to_bytes(2,'big') + _r0.to_bytes(2,'big')")
                if mb_dt == "uint32":
                    lines.append(f"                value = int.from_bytes(_raw, 'big')")
                elif mb_dt == "int32":
                    lines.append(f"                value = int.from_bytes(_raw, 'big', signed=True)")
                elif mb_dt == "float32":
                    lines.append(f"                value = struct.unpack('>f', _raw)[0]")
            lines.append(f"        if value is not None:")
    elif source == "raw":
        off = b["byteOffset"]
        dt = b["dataType"]
        bo_str = b.get("byteOrder", "大端(BE)")
        fh = b.get("frameHeader", "").replace(" ", "")
        ft = b.get("frameTail", "").replace(" ", "")
        raw_var = "raw"
        if fh or ft:
            lines.append(f"        _payload = raw")
            if fh:
                lines.append(f"        _hdr = bytes.fromhex({repr(fh)})")
                lines.append(f"        _hi = _payload.find(_hdr)")
                lines.append(f"        if _hi < 0: return")
                lines.append(f"        _payload = _payload[_hi + len(_hdr):]")
            if ft:
                lines.append(f"        _tlr = bytes.fromhex({repr(ft)})")
                lines.append(f"        _ti = _payload.find(_tlr)")
                lines.append(f"        if _ti < 0: return")
                lines.append(f"        _payload = _payload[:_ti]")
            raw_var = "_payload"
        if dt == "ASCII":
            lines.append(f"        if len({raw_var}) > {off}:")
            lines.append(f"            value = {raw_var}[{off}:{raw_var}.find(0, {off}) if {raw_var}.find(0, {off}) >= 0 else len({raw_var})].decode('ascii', errors='replace')")
        else:
            fmt_info = {"uint8": ("B", 1), "int8": ("b", 1), "uint16": ("H", 2),
                        "int16": ("h", 2), "uint32": ("I", 4), "int32": ("i", 4),
                        "float32": ("f", 4)}.get(dt, ("H", 2))
            bo = ">" if bo_str == "大端(BE)" else "<"
            lines.append(f"        if len({raw_var}) >= {off + fmt_info[1]}:")
            lines.append(f"            value = struct.unpack('{bo}{fmt_info[0]}', {raw_var}[{off}:{off + fmt_info[1]}])[0]")

    indent = "            " if source == "parsed" else "            "

    if expr:
        lines.append(f"{indent}try:")
        lines.append(f"{indent}    value = eval({repr(expr)}, {{'__builtins__': {{}}}}, {{'value': value}})")
        lines.append(f"{indent}except Exception: pass")

    need_format = dfmt != "自动" and wtype in ("Label", "LineEdit", "NumericDisplay")
    if need_format:
        lines.append(f"{indent}value = _format_display(value, {repr(dfmt)})")

    lines.append(f"{indent}w = self.ui.widgets.get('{wid}')")
    lines.append(f"{indent}if w:")

    if wtype in ("Label", "LineEdit"):
        lines.append(f"{indent}    w.setText(str(value))")
    elif wtype == "NumericDisplay":
        lines.append(f"{indent}    w.set_value(str(value))")
    elif wtype == "LEDIndicator":
        on_val = b.get("onValue", "1")
        off_val = b.get("offValue", "0")
        lines.append(f"{indent}    _sv = str(value).strip()")
        lines.append(f"{indent}    if _sv == {repr(on_val)}: w.set_on(True)")
        lines.append(f"{indent}    elif _sv == {repr(off_val)}: w.set_on(False)")
        lines.append(f"{indent}    else:")
        lines.append(f"{indent}        try: w.set_on(float(_sv) == float({repr(on_val)}))")
        lines.append(f"{indent}        except (ValueError, TypeError): w.set_on(bool(_sv))")
    elif wtype in ("ProgressBar", "ProgressRingDisplay"):
        lines.append(f"{indent}    w.setValue(int(value))")
    elif wtype == "GaugeMeter":
        lines.append(f"{indent}    w.set_value(float(value))")
    elif wtype in ("Slider", "SpinBox"):
        lines.append(f"{indent}    w.setValue(int(value))")
    elif wtype == "ToggleSwitch":
        lines.append(f"{indent}    w.setChecked(bool(value))")
    else:
        lines.append(f"{indent}    if hasattr(w, 'setText'): w.setText(str(value))")
    lines.append("")


