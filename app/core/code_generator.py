def _gen_widgets_recursive(widgets: list, lines: list, parent_var: str):
    """Recursively generate widget creation code, handling nested children."""
    for w in widgets:
        wid = w["id"]
        wtype = w["type"]
        props = w.get("properties", {})
        geo = w.get("geometry", {})
        x, y = int(geo.get("x", 0)), int(geo.get("y", 0))
        width, height = int(geo.get("w", 120)), int(geo.get("h", 40))

        create_code = _widget_create_code(wid, wtype, props, parent_var)
        lines.append(f"        {create_code}")
        lines.append(f"        self.widgets['{wid}'].setGeometry({x}, {y}, {width}, {height})")
        lines.append(f"        self.widgets['{wid}'].show()")

        cmd_lines = _gen_command_connection(wid, wtype, props)
        if cmd_lines:
            lines += cmd_lines

        if props.get("notify"):
            lines += _gen_notify_connection(wid, wtype, props)

        lines.append("")

        children = w.get("children", [])
        if children:
            if wtype == "TabWidget":
                from collections import defaultdict
                tabs = defaultdict(list)
                for c in children:
                    tabs[c.get("tabIndex", 0)].append(c)
                for ti, tab_children in sorted(tabs.items()):
                    page_var = f"self.widgets['{wid}'].widget({ti})"
                    _gen_widgets_recursive(tab_children, lines, page_var)
            else:
                child_parent = f"self.widgets['{wid}']"
                _gen_widgets_recursive(children, lines, child_parent)


_NEWLINE_CODE_MAP = {"无": "", "\\r\\n": "\r\n", "\\n": "\n", "\\r": "\r"}
_NOTIFY_TYPE_MAP = {"成功": "success", "信息": "info", "警告": "warning", "错误": "error"}
_FC_NAME_MAP = {
    "01 读线圈": 0x01, "02 读离散输入": 0x02,
    "03 读保持寄存器": 0x03, "04 读输入寄存器": 0x04,
    "05 写单线圈": 0x05, "06 写单寄存器": 0x06,
}


def _gen_command_connection(wid: str, wtype: str, props: dict) -> list:
    """Generate serial command connection lines for a widget."""
    mode = props.get("commandMode", "文本")
    newline = props.get("commandNewline", "\\r\\n")
    suffix = _NEWLINE_CODE_MAP.get(newline, "\r\n")
    tpl = props.get("commandTemplate", "{value}")
    tpl_repr = repr(tpl)
    fh = props.get("frameHeader", "").strip()
    ft = props.get("frameTail", "").strip()
    dtype = props.get("dataType", "HEX字符串")
    border = props.get("byteOrder", "大端(BE)")
    w_ref = f"self.widgets['{wid}']"
    result = []

    _FMT_MAP = {"uint8": "B", "int8": "b", "uint16": "H",
                "int16": "h", "uint32": "I", "int32": "i",
                "float32": "f"}
    is_struct = dtype in _FMT_MAP

    def _tpl_send(val_expr: str) -> str:
        """Generate a template-aware send expression."""
        if mode == "HEX" and is_struct:
            fmt = _FMT_MAP[dtype]
            bo = ">" if border == "大端(BE)" else "<"
            cast = "float" if dtype == "float32" else "int"
            return (f"self._send_packed_value({val_expr}, "
                    f"{repr(bo + fmt)}, {cast}, {tpl_repr}, {repr(fh)}, {repr(ft)})")
        if tpl == "{value}":
            raw_expr = val_expr
        else:
            raw_expr = f"{tpl_repr}.replace('{{value}}', str({val_expr}))"
        if mode == "HEX":
            return f"self._send_hex_command({raw_expr}, {repr(fh)}, {repr(ft)})"
        return f"self._send_text_command({raw_expr}, {repr(suffix)})"

    def _modbus_send(val_expr: str) -> str:
        slave = int(props.get("mbSlave", 1))
        fc = _FC_NAME_MAP.get(props.get("mbFunc", "06 写单寄存器"), 0x06)
        addr = int(props.get("mbAddress", 0))
        return f"self._send_modbus({slave}, {fc}, {addr}, int({val_expr}))"

    if wtype == "PushButton":
        cmd = props.get("command", "").strip()
        if mode == "Modbus":
            slave = int(props.get("mbSlave", 1))
            fc = _FC_NAME_MAP.get(props.get("mbFunc", "03 读保持寄存器"), 0x03)
            addr = int(props.get("mbAddress", 0))
            val = int(props.get("mbValue", 1))
            result.append(
                f"        {w_ref}.clicked.connect("
                f"lambda: self._send_modbus({slave}, {fc}, {addr}, {val}))")
        elif cmd:
            result.append(
                f"        {w_ref}.clicked.connect("
                f"lambda: {_tpl_send(repr(cmd))})")

    elif wtype == "ToggleSwitch":
        on_cmd = props.get("onCommand", "").strip()
        off_cmd = props.get("offCommand", "").strip()
        if mode == "Modbus":
            slave = int(props.get("mbSlave", 1))
            addr = int(props.get("mbAddress", 0))
            result.append(
                f"        {w_ref}.checkedChanged.connect("
                f"lambda c: self._send_modbus({slave}, 5, {addr}, "
                f"0xFF00 if c else 0x0000))")
        elif on_cmd or off_cmd:
            result.append(
                f"        {w_ref}.checkedChanged.connect("
                f"lambda c: {_tpl_send(repr(on_cmd))} "
                f"if c else {_tpl_send(repr(off_cmd))})")

    elif wtype == "LineEdit" and (props.get("sendOnEnter") or mode == "Modbus"):
        if mode == "Modbus":
            result.append(
                f"        {w_ref}.returnPressed.connect("
                f"lambda: {_modbus_send(f'{w_ref}.text().strip() or 0')})")
        else:
            result.append(
                f"        {w_ref}.returnPressed.connect("
                f"lambda: {_tpl_send(f'{w_ref}.text().strip()')})")

    elif wtype == "ComboBox" and (props.get("sendOnSelect") or mode == "Modbus"):
        if mode == "Modbus":
            cmd_lines = [s.strip() for s in props.get("commands", "").split("\n")]
            cmds_repr = repr(cmd_lines)
            result.append(f"        _cmds_{wid} = {cmds_repr}")
            val_expr = (f"(int(_cmds_{wid}[i]) if i < len(_cmds_{wid}) and _cmds_{wid}[i] "
                        f"else int({w_ref}.currentText() or 0))")
            result.append(
                f"        {w_ref}.currentIndexChanged.connect("
                f"lambda i: {_modbus_send(val_expr)})")
        else:
            cmd_lines = [s.strip() for s in props.get("commands", "").split("\n")]
            cmds_repr = repr(cmd_lines)
            result.append(
                f"        _cmds_{wid} = {cmds_repr}")
            val_expr = (f"(_cmds_{wid}[i] if i < len(_cmds_{wid}) and _cmds_{wid}[i] "
                        f"else {w_ref}.currentText())")
            result.append(
                f"        {w_ref}.currentIndexChanged.connect("
                f"lambda i: {_tpl_send(val_expr)})")

    elif wtype in ("Slider", "SpinBox") and (props.get("sendOnChange") or mode == "Modbus"):
        if mode == "Modbus":
            result.append(
                f"        {w_ref}.valueChanged.connect("
                f"lambda v: {_modbus_send('v')})")
        else:
            result.append(
                f"        {w_ref}.valueChanged.connect("
                f"lambda v: {_tpl_send('v')})")

    return result


def _gen_notify_connection(wid: str, wtype: str, props: dict) -> list:
    """Generate notification connection lines for a widget."""
    title = repr(props.get("notifyTitle", "提示"))
    content = repr(props.get("notifyContent", ""))
    ntype = _NOTIFY_TYPE_MAP.get(props.get("notifyType", "信息"), "info")
    duration = int(props.get("notifyDuration", 3000))
    w_ref = f"self.widgets['{wid}']"
    cb = (f"lambda: InfoBar.{ntype}(title={title}, content={content}, "
          f"orient=Qt.Horizontal, isClosable=True, "
          f"position=InfoBarPosition.TOP, duration={duration}, parent=self)")
    result = []
    if wtype == "PushButton":
        result.append(f"        {w_ref}.clicked.connect({cb})")
    elif wtype == "ToggleSwitch":
        result.append(f"        {w_ref}.checkedChanged.connect({cb})")
    return result


def _widget_create_code(wid: str, wtype: str, props: dict, parent_var: str = "self._page") -> str:
    """Return Python code line(s) to create a widget."""
    p = lambda k, d="": repr(props.get(k, d))
    pv = parent_var

    if wtype == "PushButton":
        return f"self.widgets['{wid}'] = PushButton({p('text', '按钮')}, {pv})"
    if wtype == "Label":
        alignment = {"Left": "Qt.AlignLeft | Qt.AlignVCenter",
                     "Center": "Qt.AlignCenter",
                     "Right": "Qt.AlignRight | Qt.AlignVCenter"}.get(
                         props.get("alignment", "Left"), "Qt.AlignLeft | Qt.AlignVCenter")
        return (f"self.widgets['{wid}'] = BodyLabel({p('text', '标签')}, {pv}); "
                f"_font = self.widgets['{wid}'].font(); "
                f"_font.setPointSize({int(props.get('fontSize', 14))}); "
                f"_font.setBold({bool(props.get('bold', False))!r}); "
                f"self.widgets['{wid}'].setFont(_font); "
                f"self.widgets['{wid}'].setAlignment({alignment})")
    if wtype == "LineEdit":
        return (f"self.widgets['{wid}'] = LineEdit({pv}); "
                f"self.widgets['{wid}'].setPlaceholderText({p('placeholderText', '')})")
    if wtype == "ComboBox":
        items = [s.strip() for s in props.get("items", "").split("\n") if s.strip()]
        return (f"self.widgets['{wid}'] = ComboBox({pv}); "
                f"self.widgets['{wid}'].addItems({repr(items)})")
    if wtype == "ToggleSwitch":
        lbl = props.get("label", "开关")
